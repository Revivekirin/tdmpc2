    x=paired[paired.kind=='shifted'].merge(frozen[['family','severity','seed','episode_return']],
        left_on=['family','severity','evaluation_seed'],right_on=['family','severity','seed'],validate='many_to_one')
    assert len(x)==1440 and np.allclose(x.Frozen_episode_return,x.episode_return,rtol=0,atol=1e-9)
    # Four method values must match the raw-to-report canonical measurements.
    for method,column in zip(METHODS,('Frozen','Dynamics-only','Dynamics+Q','Joint RL')):
        c=canonical[(canonical.kind=='shifted')&(canonical.method==method)&(canonical.metric=='episode_return')]
